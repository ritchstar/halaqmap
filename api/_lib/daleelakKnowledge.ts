// ── بناء المعرفة كنص للحقن في System Prompt ─────────────────────────────

function productBlockAr(p: DaleelakProductEntry): string {
  const lines = [
    `▸ ${p.nameAr} [${p.code}] — مستوى الدليل: ${p.evidenceLevel}`,
    `  الأنسب له: ${p.bestForAr}`,
    `  نمط الحضور: ${p.presenceModesAr.join('، ')}`,
    `  نمط الطلب: ${p.orderModesAr.join('، ')}`,
    `  المشكلة: ${p.customerProblemAr}`,
    `  نقطة البيع: ${p.primaryValueAr}`,
    `  مثال جملة: ${p.approvedPitchAr}`,
    `  أسئلة التأهيل: ${p.qualifyingQuestionsAr.join(' / ')}`,
    `  غير مناسب عندما: ${p.notForAr}`,
  ];
  if (p.objections.length > 0) {
    lines.push(`  اعتراض شائع: ${p.objections.map((o) => `«${o.qAr}» ← ${o.aAr}`).join(' | ')}`);
  }
  if (p.requiresLiveVerificationAr) {
    lines.push(`  ⚠️ تحقق قبل الوعد: ${p.requiresLiveVerificationAr}`);
  }
  return lines.join('\n');
}

/**
 * يبني كتلة معرفة المنتجات الكاملة نصاً — تُستدعى من system prompt الوكيل.
 * لا RAG ولا embeddings: الكتالوج صغير بما يكفي ليُحقن كاملاً كنص، ويتحدّث
 * تلقائياً مع أي تعديل مستقبلي على هذا الملف دون الحاجة لإعادة فهرسة.
 */
export function buildDaleelakProductKnowledgeBlockAr(): string {
  return DALEELAK_PRODUCTS.map(productBlockAr).join('\n\n');
}


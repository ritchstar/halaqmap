export function grocersCatalogById(id: string): StoreGrocersCatalogItem | undefined {
  return STORE_GROCERS_CATALOG.find((item) => item.id === id);
}

export function parseGrocersListText(raw: string): Array<{ nameAr: string; price: number }> {
  return String(raw || '')
    .split(/\r?\n/)
    .map((line) => line.replace(/\s+/g, ' ').trim())
    .filter(Boolean)
    .map((line) => {
      const match = line.match(/^(.*?)[\s:—-]+(\d+(?:\.\d{1,2})?)\s*$/);
      if (!match) return { nameAr: line.slice(0, 80), price: 0 };
      return { nameAr: match[1].trim().slice(0, 80), price: Number(match[2]) };
    })
    .filter((row) => row.nameAr.length >= 2);
}

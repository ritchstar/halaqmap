export type StoreGrocersCatalogItem = {
  id: string;
  nameAr: string;
  category: string;
  defaultPrice: number;
};

type Seed = readonly [nameAr: string, price: number];

function expand(category: string, seeds: readonly Seed[], prefix: string): StoreGrocersCatalogItem[] {
  return seeds.map(([nameAr, defaultPrice], index) => ({
    id: `${prefix}-${index + 1}`,
    nameAr,
    category,
    defaultPrice,
  }));
}

